// 对话设置卡片上的服务商标识。
// 轮廓按官方矢量重导。OpenAI / ChatGPT 用黑色花结，不沿用旧的紫色填色。近黑标识跟着界面墨色走。

struct ProviderLogo: View {
    let provider: AgentProviderID
    var dimmed: Bool = false

    var body: some View {
        let side: CGFloat = dimmed ? 34 : 52
        Group {
            if provider == .google {
                GeminiSparkle()
                    .frame(width: side, height: side)
                    .grayscale(dimmed ? 1 : 0)
                    .opacity(dimmed ? 0.55 : 1)
            } else if let mark = ProviderMarks.mark(for: provider) {
                ProviderMarkShape(path: mark.path)
                    .fill(mark.monochrome ? WeiBeiTheme.ink : mark.color, style: FillStyle(eoFill: true))
                    .frame(width: side, height: side)
                    .grayscale(dimmed ? 1 : 0)
                    .opacity(dimmed ? 0.55 : 1)
            } else {
                RoundedRectangle(cornerRadius: dimmed ? 7 : 10, style: .continuous)
                    .strokeBorder(WeiBeiTheme.hairline.opacity(dimmed ? 0.35 : 0.55), lineWidth: 1)
                    .frame(width: side, height: side)
            }
        }
        .accessibilityLabel(Text(provider.rawValue))
    }
}

/// Gemini 四色星：蓝底，再叠绿、红、黄三层从尖角淡向中心。坐标跟 24 视框对齐。
private struct GeminiSparkle: View {
    var body: some View {
        let shape = ProviderMarkShape(path: ProviderMarks.gemini)
        ZStack {
            shape.fill(Color(red: 0.192, green: 0.525, blue: 1))
            wash(shape, color: Color(red: 0.031, green: 0.725, blue: 0.384),
                 from: (7 / 24, 15.5 / 24), to: (11 / 24, 12 / 24), fade: 1)
            wash(shape, color: Color(red: 0.976, green: 0.271, blue: 0.263),
                 from: (8 / 24, 5.5 / 24), to: (11.5 / 24, 11 / 24), fade: 1)
            wash(shape, color: Color(red: 0.980, green: 0.737, blue: 0.071),
                 from: (3.5 / 24, 13.5 / 24), to: (17.5 / 24, 12 / 24), fade: 0.46)
        }
    }

    private func wash(_ shape: ProviderMarkShape, color: Color, from: (CGFloat, CGFloat), to: (CGFloat, CGFloat), fade: CGFloat) -> some View {
        shape.fill(
            LinearGradient(
                stops: [
                    .init(color: color, location: 0),
                    .init(color: color.opacity(0), location: fade),
                ],
                startPoint: UnitPoint(x: from.0, y: from.1),
                endPoint: UnitPoint(x: to.0, y: to.1)
            )
        )
    }
}

private struct ProviderMarkShape: Shape {
    let path: Path

    func path(in rect: CGRect) -> Path {
        let scale = min(rect.width, rect.height) / 24
        let tx = rect.midX - 12 * scale
        let ty = rect.midY - 12 * scale
        let transform = CGAffineTransform(translationX: tx, y: ty)
            .concatenating(CGAffineTransform(scaleX: scale, y: scale))
        return path.applying(transform)
    }
}

